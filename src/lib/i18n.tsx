const LocaleContext = createContext<Locale>("en");

export function localeFromPathname(pathname: string | null): Locale {
  if (pathname?.startsWith("/pt") && (pathname === "/pt" || pathname.startsWith("/pt/"))) return "pt";
  if (pathname?.startsWith("/es") && (pathname === "/es" || pathname.startsWith("/es/"))) return "es";
  return "en";
}

export function getMessage(locale: Locale, key: string, value?: string): string {
  const message = messages[locale][key] ?? englishMessages[key] ?? key;
  return typeof message === "function" ? message(value ?? "") : message;
}

